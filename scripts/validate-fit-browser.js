// Run with the Playwright browser_run_code tool's filename argument while dev is running.
async (page) => {
  await page.goto('http://localhost:3000');
  await page.getByText('Face fit estimated · adjust if needed', { exact: true }).waitFor();
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const image = () => page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  const select = async name => {
    await page.getByRole('img', { name, exact: true }).last().click();
    await settle();
  };
  await select('Mayura 22KT Peacock Bell Jhumkas');
  await page.getByRole('button', { name: 'Fit controls', exact: true }).click();
  await settle();
  const automatic = await image();
  await page.getByRole('button', { name: 'Increase ornament size' }).click();
  await settle();
  assert(await image() !== automatic, 'Size button must change the rendered jewelry.');
  await page.getByRole('button', { name: 'Reset fit' }).click();
  await settle();
  assert(await image() === automatic, 'Reset must restore the detected fit, not fallback coordinates.');
  await page.getByRole('button', { name: 'Set two fit points' }).click();
  await page.locator('canvas').scrollIntoViewIfNeeded();
  const box = await page.locator('canvas').boundingBox();
  await page.locator('canvas').click({ position: { x: box.width * .3, y: box.height * .43 } });
  assert(await page.getByRole('status').innerText().then(t => t.includes('1/2')), 'First calibration point must be recorded.');
  await page.locator('canvas').click({ position: { x: box.width * .72, y: box.height * .44 } });
  await settle();
  assert(await page.getByRole('status').count() === 0, 'Two points must complete calibration.');
  assert(await image() !== automatic, 'Calibration must change the render.');
  await page.getByRole('button', { name: 'Reset fit' }).click();
  await settle();
  assert(await image() === automatic, 'Reset must also clear calibration.');
  await page.locator('canvas').scrollIntoViewIfNeeded();
  const dragBox = await page.locator('canvas').boundingBox();
  await page.mouse.move(dragBox.x + dragBox.width * .5, dragBox.y + dragBox.height * .55);
  await page.mouse.down();
  await page.mouse.move(dragBox.x + dragBox.width * .5 + 20, dragBox.y + dragBox.height * .55 + 30, { steps: 4 });
  await page.mouse.up();
  assert(Math.abs(Number(await page.getByRole('slider', { name: 'Horizontal position' }).inputValue()) - 20 / dragBox.width) < .003, 'Drag must preserve the grab offset.');
  await page.getByRole('button', { name: 'Reset fit' }).click();
  await page.getByRole('button', { name: 'Compare original' }).click();
  assert(await page.getByRole('img', { name: 'Original photo', exact: true }).isVisible(), 'Compare must show the original photograph.');
  await page.getByRole('button', { name: 'Compare original' }).click();
  await select('Aura 18KT Diamond Solitaire Ring');
  await page.getByText('Hand fit estimated · adjust if needed', { exact: true }).waitFor();
  await settle();
  const ring = await image();
  await page.getByRole('slider', { name: 'Ornament rotation' }).fill('30');
  await settle();
  assert(await image() !== ring, 'The ring must respond to rotation.');
  await page.getByRole('button', { name: 'Reset fit' }).click();
  await settle();
  assert(await image() === ring, 'The ring must reset to its finger-aligned orientation.');
  await page.setViewportSize({ width: 375, height: 812 });
  await settle();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Small phone must not overflow horizontally.');
  await page.setViewportSize({ width: 812, height: 375 });
  await settle();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Landscape must not overflow horizontally.');
  await page.setViewportSize({ width: 1100, height: 1000 });
  return 'Passed: sizing, automatic reset, two-point calibration, calibration reset, drag offset, comparison, ring rotation, 375px phone and landscape layout.';
}
